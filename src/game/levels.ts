import { ARENA_HEIGHT, ARENA_WIDTH, BumperDef, LevelDef, TapeDef, TapeVariant, WallDef, WallType } from './types';

function rectWall(
  id: string,
  left: number,
  top: number,
  w: number,
  h: number,
  type: WallType = 'solid',
  bounceFactor?: number,
  minBounceSpeed?: number
): WallDef {
  return {
    id,
    x: left + w / 2,
    y: top + h / 2,
    w,
    h,
    angle: 0,
    type,
    bounceFactor,
    minBounceSpeed,
  };
}

function angledWall(
  id: string,
  cx: number,
  cy: number,
  w: number,
  h: number,
  angleDeg: number,
  type: WallType = 'elastic',
  bounceFactor?: number,
  minBounceSpeed?: number
): WallDef {
  return {
    id,
    x: cx,
    y: cy,
    w,
    h,
    angle: (angleDeg * Math.PI) / 180,
    type,
    bounceFactor,
    minBounceSpeed,
  };
}

function tape(
  id: string,
  cx: number,
  cy: number,
  w: number,
  h: number,
  angleDeg = 0,
  variant: TapeVariant = 'masking',
  move?: { axis: 'x' | 'y'; range: number; speed: number; phase?: number },
  spinSpeed?: number
): TapeDef {
  return {
    id,
    x: cx,
    y: cy,
    w,
    h,
    angle: (angleDeg * Math.PI) / 180,
    variant,
    moveAxis: move?.axis,
    moveRange: move?.range,
    moveSpeed: move?.speed,
    movePhase: move?.phase ?? 0,
    spinSpeed,
  };
}

function bumper(id: string, x: number, y: number, radius = 26, power = 540): BumperDef {
  return { id, x, y, radius, power };
}

function frameWalls(
  topType: WallType = 'solid',
  rightType: WallType = 'solid',
  bottomType: WallType = 'solid',
  leftType: WallType = 'solid'
): WallDef[] {
  const t = 24;
  return [
    rectWall('frame-top', 0, 0, ARENA_WIDTH, t, topType),
    rectWall('frame-bottom', 0, ARENA_HEIGHT - t, ARENA_WIDTH, t, bottomType),
    rectWall('frame-left', 0, t, t, ARENA_HEIGHT - t * 2, leftType),
    rectWall('frame-right', ARENA_WIDTH - t, t, t, ARENA_HEIGHT - t * 2, rightType),
  ];
}

